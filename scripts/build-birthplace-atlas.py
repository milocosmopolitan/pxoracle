#!/usr/bin/env python3
"""Deterministic, offline transformation of the attributed, pinned GeoNames world snapshot."""
import gzip
import hashlib
import json
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "content/astrology/atlas"
PUBLIC = ROOT / "apps/web/public/content/atlas"
def output(path, data):
    if "--check" in sys.argv:
        assert path.read_bytes() == data, f"Stale generated atlas: {path}"
    else:
        path.write_bytes(data)

provenance = json.loads((SOURCE / "provenance.json").read_text())
for name, expected in provenance["snapshotSha256"].items():
    assert hashlib.sha256((SOURCE / name).read_bytes()).hexdigest() == expected, name
admin = {r[0]: r[1] for line in (SOURCE / "source-admin1.tsv").read_text().splitlines() if (r := line.split("\t"))}
rows = [line.split("\t") for line in gzip.decompress((SOURCE / "source-world.tsv.gz").read_bytes()).decode().splitlines()]
manifest = {"version": provenance["version"], "license": "CC-BY-4.0", "attribution": "GeoNames", "countries": {}}
PUBLIC.mkdir(parents=True, exist_ok=True)
labels = {r[0]: r[4] for line in (SOURCE / "source-countries.tsv").read_text().splitlines()
          if not line.startswith("#") and (r := line.split("\t")) and len(r) > 4}
countries = {code: labels[code] for code in sorted({r[8] for r in rows})}
for country, label in countries.items():
    cities = []
    for r in rows:
        if r[8] != country:
            continue
        assert r[17] and "/" in r[17], "Missing explicit IANA zone"
        aliases = sorted(set([r[2]] + r[3].split(",")) - {"", r[1]})
        cities.append([r[0], r[1], admin.get(country + "." + r[10], label),
                       float(r[4]), float(r[5]), r[17], aliases])
    cities.sort(key=lambda r: int(r[0]))
    name = country + "." + provenance["version"] + ".json"
    data = json.dumps({"version": provenance["version"], "country": country, "cities": cities},
                      ensure_ascii=False, separators=(",", ":")).encode()
    output(PUBLIC / name, data)
    manifest["countries"][country] = {"label": label, "file": name, "count": len(cities), "bytes": len(data),
                                     "gzipBytes": len(gzip.compress(data, mtime=0)), "sha256": hashlib.sha256(data).hexdigest()}
    print(country, len(cities), "cities;", len(data), "bytes;", manifest["countries"][country]["gzipBytes"], "gzip")
output(PUBLIC / ("manifest." + provenance["version"] + ".json"), (json.dumps(manifest, indent=2) + "\n").encode())
output(SOURCE / ("manifest." + provenance["version"] + ".json"), (json.dumps(manifest, indent=2) + "\n").encode())
output(PUBLIC / "GEONAMES-LICENSE.txt", (SOURCE / "GEONAMES-LICENSE.txt").read_bytes())

catalog = "// Generated by scripts/build-birthplace-atlas.py; labels follow the pinned GeoNames source.\n"
catalog += "export const ATLAS_COUNTRIES = " + json.dumps(countries, ensure_ascii=False, indent=2) + " as const;\n"
catalog += f"export const ATLAS_CITY_COUNT = {len(rows)};\n"
output(ROOT / "packages/contracts/src/atlas-countries.ts", catalog.encode())
