import { chromium } from "playwright";
import { mkdir, writeFile, rm } from "node:fs/promises";
const origin = process.env.PXORACLE_CAPTURE_URL ?? "http://127.0.0.1:3010";
const destination = "docs/validation/globe-lighting";
await mkdir(destination, { recursive: true });
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, recordVideo: { dir: `${destination}/raw-video`, size: { width: 1440, height: 1000 } } });
const page = await context.newPage();
const errors = [];
page.on("pageerror", e => errors.push(e.message));
await page.goto(`${origin}/astrology/`);
await page.locator(".scene-status").waitFor({ state: "hidden", timeout: 60000 });
const skip = page.getByRole("button", { name: "Skip entrance →" });
if (await skip.isVisible()) await skip.click();
await page.locator(".door-entrance").waitFor({ state: "hidden" });
await page.waitForTimeout(1200);
await page.screenshot({ path: `${destination}/room-integrated.png` });
await page.getByRole("button", { name: "Explore the globe", exact: true }).click();
await page.waitForTimeout(1600);
await page.screenshot({ path: `${destination}/globe-approach.png` });
await page.getByLabel("Browsing region").selectOption("asia");
await page.waitForTimeout(1600);
await page.screenshot({ path: `${destination}/globe-region-asia.png` });
for (const country of ["RU", "SG", "FJ", "IS"]) {
  await page.getByLabel("Browsing region").selectOption("");
  await page.getByLabel("Birth country").selectOption(country);
  await page.waitForTimeout(1700);
  await page.screenshot({ path: `${destination}/globe-country-${country.toLowerCase()}.png` });
}
await page.getByLabel("Birth country").selectOption("SG");
await page.getByLabel("Birth city", { exact: true }).fill("Singapore");
await page.getByRole("button", { name: /Singapore.*Asia\/Singapore/ }).first().click();
await page.waitForTimeout(1800);
await page.screenshot({ path: `${destination}/globe-city-selected.png` });
await page.getByRole("button", { name: "Back one view" }).click();
await page.waitForTimeout(1400);
await page.getByRole("button", { name: "Room view" }).click();
await page.waitForTimeout(1400);
const video = page.video();
await context.close();
await video.saveAs(`${destination}/globe-forward-back.webm`);
const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true, reducedMotion: "reduce" });
const mobilePage = await mobile.newPage();
await mobilePage.goto(`${origin}/astrology/`);
await mobilePage.getByLabel("Birth country").selectOption("FJ");
await mobilePage.waitForTimeout(1200);
await mobilePage.screenshot({ path: `${destination}/globe-mobile-emulation.png`, fullPage: true });
await mobile.close();
const storyOrigin = process.env.PXORACLE_STORY_URL ?? "http://localhost:6007";
const inspection = await browser.newPage({ viewport: { width: 1100, height: 800 }, reducedMotion: "reduce" });
inspection.on("pageerror", e => errors.push(e.message));
for (const [story, filename] of [["front", "lamp-all-lights"], ["shade-only", "lamp-shade-only"], ["no-shadows", "lamp-no-shadows"]]) {
  await inspection.goto(`${storyOrigin}/iframe.html?id=room-production-lighting--${story}&viewMode=story`);
  await inspection.getByText("Ready").waitFor();
  await inspection.screenshot({ path: `${destination}/${filename}.png` });
}
await inspection.close();
const tarot = await browser.newContext({ viewport: { width: 1100, height: 800 }, recordVideo: { dir: `${destination}/raw-video`, size: { width: 1100, height: 800 } } });
const table = await tarot.newPage();
table.on("pageerror", e => errors.push(e.message));
await table.goto(`${storyOrigin}/iframe.html?id=pxoracle-tarot-table--full-camera-sequence&viewMode=story`);
await table.getByText(/No WASM · conversation/).waitFor();
await table.locator(".scene-status").waitFor({ state: "hidden" });
await table.waitForTimeout(1500);
await table.screenshot({ path: `${destination}/tarot-lighting-conversation.png` });
await table.getByRole("button", { name: "Conversation / table" }).click();
await table.getByText(/No WASM · selecting/).waitFor({ timeout: 60000 });
await table.waitForTimeout(1200);
await table.screenshot({ path: `${destination}/tarot-lighting-table.png` });
await table.getByRole("button", { name: "Conversation / table" }).click();
await table.waitForTimeout(1800);
const tarotVideo = table.video();
await tarot.close();
await tarotVideo.saveAs(`${destination}/tarot-camera-lighting.webm`);
await writeFile(`${destination}/capture-browser.json`, JSON.stringify({ origin, browser: "Chromium headless", desktop: "1440x1000", mobile: "390x844 touch viewport emulation, not a physical device", lightingComparison: "Production fixtures on versus shade emissive only (ambient/window remain) versus spotlight shadows disabled", tarot: "Production TarotTable story camera approach and return; synthetic cards, no WASM", errors }, null, 2) + "\n");
await browser.close();
await rm(`${destination}/raw-video`, { recursive: true, force: true });
console.log(`Captured integrated room, country frames, navigation video and mobile emulation to ${destination}; page errors: ${errors.length}.`);
